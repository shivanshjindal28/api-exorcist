def test_connexion_and_api_first_handlers_are_found() -> None:
    files = {
        "api_views/users.py": "def debug():\n    return []\n",
        "src/main/java/x/OwnerRestController.java": (
            "@RestController\npublic class OwnerRestController implements OwnersApi {\n"
            "    @Override\n    public ResponseEntity<List<OwnerDto>> listOwners(String n) {\n"
            "        return null;\n    }\n}\n"),
    }
    for scan in _repo(files):
        found = find_handlers(scan, {"api_views.users.debug", "listOwners", "missingOp"})
    assert found["api_views.users.debug"].file == "api_views/users.py"
    assert found["listOwners"].file.endswith("OwnerRestController.java")
    assert "missingOp" not in found


