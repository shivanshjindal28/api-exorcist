GENERATED = """// This file is auto-generated by @hey-api/openapi-ts
export class UsersService {
    public static readUsers(options) {
        return client.get<R>({ url: '/api/v1/users/', ...options });
    }
    public static createUser(options) {
        return client.post<R>({ url: '/api/v1/users/', ...options });
    }
}
export class PrivateService {
    public static createUser(options) {
        return client.post<R>({ url: '/api/v1/private/users/', ...options });
    }
}
"""
APP = """import { UsersService } from "@/client"
export const load = () => UsersService.readUsers({})
export const add = (u) => UsersService.createUser({ body: u })
"""


def test_generated_client_functions_count_only_when_called() -> None:
    for scan in _repo({"frontend/src/client/sdk.gen.ts": GENERATED,
                       "frontend/src/routes/users.tsx": APP}):
        refs = collect_client_refs(scan)
    called = {(r.method, r.path) for r in refs.refs}
    assert ("GET", "/api/v1/users") in called and ("POST", "/api/v1/users") in called
    # Same function name, different class: PrivateService.createUser is not called.
    assert [(n, p) for n, _, p in refs.uncalled_generated] == [
        ("createUser", "/api/v1/private/users")]


