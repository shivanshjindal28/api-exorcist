@pytest.mark.parametrize("raw,concat,want", [
    ("api/auth/v3/check-otp", False, "/api/auth/v3/check-otp"),          # crAPI web
    ("api/v2/user/videos/<videoId>", False, "/api/v2/user/videos/{param}"),
    ("/api/v1/users/", False, "/api/v1/users"),                          # FastAPI spelling
    ("/api/accounts/", True, "/api/accounts/{param}"),                   # "/x/" + id
    ("${BASE}/api/x/${id}", False, "/{param}/api/x/{param}"),
    ("./components/Thing", False, None),
    ("/static/app.js", False, None),
    ("/users", False, None),                                             # too little to mean anything
])
def test_paths_as_clients_write_them(raw: str, concat: bool, want: str | None) -> None:
    assert _clean(raw, concatenated=concat) == want


def test_a_parameter_beats_a_word_when_matching() -> None:
    """/users/{param} is /users/{user_id}, not /users/me. It used to tie, and
    the tie hid the front end's deleteUser()."""
    eps = [("DELETE /api/v1/users/{user_id}", "DELETE", "/api/v1/users/{user_id}", "backend"),
           ("DELETE /api/v1/users/me", "DELETE", "/api/v1/users/me", "backend")]
    ref = ClientRef("frontend", "/api/v1/users/{param}", "DELETE", "f.tsx", 1, "x")
    assert [eid for _, eid in match_refs([ref], eps)] == ["DELETE /api/v1/users/{user_id}"]
    assert ref_score("/api/v1/users/{param}", "/api/v1/users/{user_id}") > \
        ref_score("/api/v1/users/{param}", "/api/v1/users/me")


def test_a_service_naming_its_own_routes_is_not_a_client() -> None:
    eps = [("POST /api/auth/v2/check-otp", "POST", "/api/auth/v2/check-otp", "identity")]
    own = ClientRef("identity", "/api/auth/v2/check-otp", "ANY", "SecurityConfig.java", 9, "x")
    web = ClientRef("web", "/api/auth/v2/check-otp", "ANY", "api.ts", 3, "x")
    assert match_refs([own], eps) == []
    assert len(match_refs([web], eps)) == 1


def test_monorepo_services_are_named_by_their_folder() -> None:
    assert service_of("services/identity/src/A.java") == "identity"
    assert service_of("backend/app/main.py") == "backend"
    assert service_of("main.py") == "root"


