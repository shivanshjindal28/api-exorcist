def _ep(eid: str, service: str = "identity", **kw: Any) -> dict[str, Any]:
    method, path = eid.split(" ", 1)
    return {"id": eid, "method": method, "path": path, "service": service,
            "documented": kw.get("documented", True), "deprecated_in_spec": kw.get("dep", False),
            "last_change_days": kw.get("age", 30), "function": kw.get("fn")}


def _rank(endpoints: list[dict[str, Any]], **kw: Any) -> dict[str, Any]:
    args: dict[str, Any] = dict(referenced={}, frontend_referenced=set(),
                                called_by_services={}, uncalled_generated={},
                                exposed_via={}, markers={}, newest_change_days=10)
    args.update(kw)
    return {c.endpoint_id: c for c in rank(endpoints, **args)}


def test_versions_are_read_from_any_segment() -> None:
    assert version_key("/identity/api/auth/v2.7/user/login") == ("/identity/api/auth/user/login", 2.7)
    assert version_key("/owners") is None


def test_crapi_shape_superseded_and_unused_is_a_likely_zombie() -> None:
    old, new = "POST /api/auth/v2/check-otp", "POST /api/auth/v3/check-otp"
    others = [_ep(f"GET /api/x{i}") for i in range(4)]
    refs = {new: ["web/api.ts:3"]} | {e["id"]: ["web/api.ts:9"] for e in others}
    c = _rank([_ep(old, age=700), _ep(new), *others], referenced=refs,
              frontend_referenced=set(refs))
    assert c[old].label == "Likely zombie" and c[old].score >= 7
    assert new not in c


def test_unversioned_path_beside_v2_is_the_old_version() -> None:
    c = _rank([_ep("GET /api/owners"), _ep("GET /api/v2/owners")])
    assert c["GET /api/owners"].label == "Superseded version"
    assert "GET /api/v2/owners" not in c


def test_probes_and_root_are_never_candidates() -> None:
    eps = [_ep(f"GET {p}", documented=False, age=900)
           for p in ("/", "/health", "/identity/api/auth/jwks.json", "/actuator/health")]
    eps.append(_ep("GET /api/real", documented=True))
    eps.append(_ep("GET /api/real2", documented=True))
    assert _rank(eps) == {}


def test_backend_calls_are_use_but_not_front_end_coverage() -> None:
    """Banking shape: services call a few internal endpoints; the public ones
    are for outside users and must not read as unused."""
    eps = [_ep(f"POST /api/accounts/internal/{n}", service="account") for n in ("debit", "credit")]
    eps += [_ep("POST /api/accounts", service="account"), _ep("GET /api/accounts/{id}", service="account")]
    refs = {eps[0]["id"]: ["tx/Client.java:70"], eps[1]["id"]: ["tx/Client.java:103"]}
    assert _rank(eps, referenced=refs, frontend_referenced=set()) == {}


def test_admin_endpoints_are_not_judged_by_front_end_use() -> None:
    eps = [_ep(f"GET /api/v{i}/thing") for i in range(1, 2)]
    eps = [_ep(f"GET /api/item{i}") for i in range(5)] + [_ep("POST /management/admin/lockUser")]
    refs = {e["id"]: ["web/x.ts:1"] for e in eps[:5]}
    assert "POST /management/admin/lockUser" not in _rank(
        eps, referenced=refs, frontend_referenced=set(refs))


def test_debug_endpoints_and_deprecation_markers() -> None:
    c = _rank([_ep("GET /users/v1/_debug"), _ep("GET /createdb"), _ep("GET /api/ok"),
               _ep("GET /api/old")], markers={"GET /api/old": ["@Deprecated at line 4"]})
    assert c["GET /users/v1/_debug"].label == "Debug or test endpoint"
    assert c["GET /createdb"].label == "Debug or test endpoint"
    assert c["GET /api/old"].label == "Deprecated but served"
    assert "GET /api/ok" not in c


def test_code_markers_sit_on_or_just_above_the_handler() -> None:
    src = "class A {\n    @Deprecated\n    @GetMapping(\"/old\")\n    public X old() {}\n}\n"
    assert code_markers(src, 3) == ["@Deprecated at line 2"]
    assert code_markers("def fine():\n    pass\n", 1) == []


